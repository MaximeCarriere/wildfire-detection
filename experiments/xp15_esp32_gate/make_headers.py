#!/usr/bin/env python3
"""XP15 stage B, step 3 — emit the model and the test frames as C headers.

The firmware carries everything it needs in flash: no camera, no SD card, no
network. That is deliberate. The board is being asked one question -- can this
chip run this model, and does it get the same answers -- and every part that is
not the chip or the model is a way for the answer to be wrong for an uninteresting
reason.

**Frame count is a real trade-off, not a default.** Each 96x96 grayscale frame is
9,216 bytes raw and about five times that as C source text, so the full 200-frame
set becomes a nine-megabyte header that takes a long time to compile. Forty frames,
ten per category, is 368 KB and enough to detect any port that has gone wrong:
this is a correctness and timing check, not a fresh accuracy measurement, and the
accuracy measurement already exists on 4,306 frames.

Emits the int8 reference scores alongside, so the sketch can print an immediate
verdict per frame rather than making you diff a serial log by eye.

Usage
    python make_headers.py                # 10 frames per category
    python make_headers.py --per-class 50 # the whole exported set
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
WEIGHTS = REPO / "weights"
DATA = HERE / "board_data"
FW = HERE / "firmware"
TAG = "xp15hdr"

CATEGORIES = ("none", "smoke", "fire", "both")


def log(m: str) -> None:
    print(f"[{TAG}] {m}", flush=True)


def c_array(name: str, blob: bytes, per_line: int = 16) -> str:
    body = []
    for i in range(0, len(blob), per_line):
        body.append("  " + " ".join(f"0x{b:02x}," for b in blob[i:i + per_line]))
    return (f"const unsigned char {name}[] = {{\n" + "\n".join(body) +
            f"\n}};\nconst unsigned int {name}_len = {len(blob)};\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--res", type=int, default=96)
    ap.add_argument("--width", type=float, default=1.0)
    ap.add_argument("--per-class", type=int, default=10)
    args = ap.parse_args()

    import numpy as np

    FW.mkdir(exist_ok=True)
    tag = f"gate_{args.res}px_w{args.width}"

    # ---- the model -------------------------------------------------------
    blob = (WEIGHTS / f"{tag}_int8.tflite").read_bytes()
    hdr = FW / "model_data.h"
    hdr.write_text(
        "// Generated by make_headers.py -- do not edit.\n"
        f"// {tag}, int8, {len(blob)} bytes.\n"
        "#pragma once\n\n"
        "// 16-byte alignment: TFLite Micro reads the flatbuffer in place and will\n"
        "// fault on an unaligned base address on this core.\n"
        "alignas(16) " + c_array("g_model", blob))
    log(f"  model_data.h  {len(blob)/1024:.0f} KB")

    # ---- the frames ------------------------------------------------------
    t = np.load(DATA / "frames_test.npz", allow_pickle=True)
    q = np.load(DATA / "int8_scores.npz")
    content, frames, ref = t["content"], t["frames"], q["score"]

    keep = []
    for c in CATEGORIES:
        idx = np.where(content == c)[0][:args.per_class]
        keep += list(idx)
    keep = sorted(keep)
    log(f"  {len(keep)} frames, {args.per_class} per category")

    flat = frames[keep].astype("uint8").tobytes()
    lines = [
        "// Generated by make_headers.py -- do not edit.",
        f"// {len(keep)} frames of {args.res}x{args.res} grayscale, and the int8 score",
        "// each one produced off-device. The board must reproduce these.",
        "#pragma once", "",
        f"#define N_FRAMES {len(keep)}",
        f"#define FRAME_RES {args.res}",
        f"#define FRAME_BYTES {args.res * args.res}", "",
        c_array("g_frames", flat), "",
        "const float g_ref_score[N_FRAMES] = {",
        "  " + ", ".join(f"{ref[i]:.5f}" for i in keep), "};", "",
        "const char* const g_label[N_FRAMES] = {",
        "  " + ", ".join(f'"{content[i]}"' for i in keep), "};", "",
    ]
    (FW / "frames_data.h").write_text("\n".join(lines))

    # The same subset, in the same order, for check_board.py. Without this the
    # firmware's frame index (0..N-1 over the selection) has to be mapped back onto
    # the original test-set position by re-deriving the selection, and any drift
    # between the two derivations shows up as a spurious mismatch.
    np.savez_compressed(DATA / "board_subset.npz", ref_score=ref[keep],
                        content=content[keep], stems=t["stems"][keep],
                        test_index=np.array(keep))
    log(f"  frames_data.h {len(flat)/1024:.0f} KB raw "
        f"({(FW / 'frames_data.h').stat().st_size/1024/1024:.1f} MB as source)")

    total = (len(blob) + len(flat)) / 1024
    log(f"flash needed for data: {total:.0f} KB of 8 MB")


if __name__ == "__main__":
    main()
